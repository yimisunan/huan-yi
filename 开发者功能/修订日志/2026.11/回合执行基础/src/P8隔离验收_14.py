def source_change_during_settlement():
    project, service, client = fixture()
    prepared, task, context, headers = begin(service, client, 'during-settlement')
    payload = semantics(prepared)
    baseline = service.store._files()
    original = service.store._settle
    def settle_then_edit(*values):
        after = original(*values)
        path = project / 'txt文件/全局执行法典.md'
        path.write_bytes(path.read_bytes() + b'\n')

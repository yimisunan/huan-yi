def restart_after_commit():
    project, service, client = fixture()
    prepared, task, context, headers = begin(service, client, 'restart-commit')
    payload = semantics(prepared)
    audit = service._verify_audit('restart-commit', proof(service, context))
    rr._atomic(service._blob('restart-commit', '.read-audit.json'), rr._json(audit))
    rr._atomic(service._blob('restart-commit', '.result.txt'), rr._json(payload))
    with service.store._locked():
        state = service._read()
        state['jobs']['restart-commit']['status'] = 'validating'
        service._write(state)
        job = copy.deepcopy(state['jobs']['restart-commit'])
    assembled = service._assemble_result('restart-commit', job)
    first = service.store.submit(assembled)
    assert first['replayed'] is False
    restarted = ss.StoryService(project)
    restarted.start()
    job = restarted.status('restart-commit')['task']
    assert job['status'] == 'committed' and job['receipt']['replayed'] is True
    assert restarted.store._ledger()['sequence'] == 1



    job = response.get_json()['task']
    assert job['status'] == 'committed', job
    saved = json.loads(service._blob('compact-success', '.assembled.json').read_bytes())['payload']
    assert payload == before and saved['request_id'] == 'compact-success'
    assert saved['current_round'] == prepared['current_round'] and saved['base_revision'] == prepared['base_revision']
    assert saved['panel_changes'] == {} and saved['host_events'] == [] and saved['task_issue'] is None
    assert '本回内容读取工具调用次数：10' in saved['system_log']
    assert '程序记忆事实:' in saved['system_log'] and 'source_sha256:' in saved['system_log']
    assert context['assembly_memory']['layers']['L1']['count'] == prepared['memory_layers']['L1']
    assert 'momentary_ease' not in context['assembly_memory']['presence']
    receipt = job['receipt']
    replay = service.store.submit(saved)
    assert replay['replayed'] and replay['revision'] == receipt['revision']
    repeat = deliver(client, task, headers, payload, audit).get_json()['task']
    assert repeat['status'] == 'committed' and service.store._ledger()['sequence'] == 1



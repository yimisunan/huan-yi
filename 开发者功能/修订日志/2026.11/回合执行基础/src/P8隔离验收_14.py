def proof(service, context):
    calls = []
    for item in context['reading_policy']['required_reads']:
        relative = item['path']
        text = (service.root / relative).read_text(encoding='utf-8')
        calls.append({'name': 'read_file', 'parameters': {'path': relative}, 'part_id': str(len(calls)),
                      'status': 'success', 'result_text': text})
    for relative in ss.REQUIRED_BROWSE:
        calls.append({'name': 'list_files', 'parameters': {'path': relative}, 'part_id': str(len(calls)),
                      'status': 'success', 'result_text': '\n'.join(p.name for p in (service.root / relative).iterdir())})
    for relative in ss.RULES[4:]:
        calls.append({'name': 'read_file', 'parameters': {'path': relative}, 'part_id': str(len(calls)),
                      'status': 'success', 'result_text': (service.root / relative).read_text(encoding='utf-8')})
    return {'api': 'Tools.Chat.sendMessageStreaming', 'chat_id': 'isolated-chat', 'participant_id': 'isolated-reader',
            'workspace': str(service.root), 'outcome': {'type': 'committed', 'status': 'completed',
                'assistant': {'messageTimestamp': 12345}}, 'snapshot_message_timestamp': 12345,
            'started_at': 1, 'completed_at': 2, 'tools': calls}



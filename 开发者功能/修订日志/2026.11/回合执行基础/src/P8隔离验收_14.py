def negative(name, mutate_payload=None, mutate_proof=None, mutate_project=None, expected='failed'):
    project, service, client = fixture()
    prepared, task, context, headers = begin(service, client, 'negative-' + str(fixture.counter))
    payload, audit = semantics(prepared), proof(service, context)
    if mutate_payload:
        mutate_payload(payload, prepared)
    if mutate_proof:
        mutate_proof(audit)
    baseline = service.store._files()
    if mutate_project:
        mutate_project(project)
        baseline = service.store._files()
    response = deliver(client, task, headers, payload, audit)
    assert response.status_code == 200, response.get_json()
    job = response.get_json()['task']
    assert job['status'] == expected, (name, job)
    assert job['error'] and service.store._files() == baseline
    assert service.store._ledger()['sequence'] == 0
    results.append({'name': name, 'status': 'PASS', 'rejection': job['error']})
